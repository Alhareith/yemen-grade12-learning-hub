export function buildArabicOutputPolicy(subject: string): string {
  const subjectRule = subject === "رياضيات"
    ? buildStrictMathArabicRule()
    : subject === "فيزياء"
      ? "في الفيزياء اجعل الشرح عربيًا بالكامل. حافظ فقط على الرموز والوحدات العلمية القياسية التي لا يصح تعريبها مثل V وI وR وm/s، واكتب بجانبها اسم الكمية ومعنى الرمز والوحدة بالعربية."
      : subject === "كيمياء"
        ? "في الكيمياء اجعل الشرح عربيًا بالكامل ولا تعرّب الصيغ الكيميائية القياسية مثل H₂O وNaCl؛ اعرض الصيغة كما هي ثم اشرح اسم المادة والرموز والتفاعل بالعربية."
        : subject === "لغة إنجليزية"
          ? "في مادة الإنجليزية أبقِ الكلمات والجمل الإنجليزية التي يجري تعلمها كما هي، لكن اجعل الشرح والقواعد والملاحظات والتصحيح بالعربية الواضحة."
          : "استخدم العربية في الشرح والمصطلحات والعناوين، وعرّف أي رمز أو اختصار بلغة عربية بسيطة.";

  return [
    "معيار الإخراج الإلزامي:",
    "- اكتب الشرح والعناوين والخطوات بالعربية الواضحة المناسبة لطالب ثالث ثانوي في اليمن.",
    "- لا تبدأ بمقدمة عامة طويلة؛ ادخل في المطلوب مباشرة.",
    "- استخدم الأرقام العربية ٠١٢٣٤٥٦٧٨٩ في النص وترقيم الخطوات، ما لم تكن وحدة علمية أو صيغة معيارية يفسدها التحويل.",
    "- ضع كل معادلة أو قانون مهم في سطر مستقل، ثم اشرح معناه بالعربية تحت السطر عند الحاجة.",
    "- حافظ على ترتيب طرفي المعادلات ولا تسمح لاتجاه RTL بقلب العلاقات أو الأقواس.",
    `- ${subjectRule}`,
    "- اجعل الناتج مناسبًا للهاتف: فقرات قصيرة، عناوين واضحة، ومسافات بين الخطوات.",
    "- إذا لم أحدد اسم الدرس لكنني أرسلت سؤالًا أو نصًا، استنتج الموضوع من المحتوى. إذا لم تكن واثقًا، اذكر افتراضك ولا تخترع اسم درس أو معلومة من المنهج.",
  ].join("\n");
}

export function buildStrictMathArabicRule(): string {
  return [
    "قاعدة الرياضيات صارمة: اكتب الحل والترميز الرياضي بالطريقة العربية المدرسية المستخدمة في اليمن، وليس بالترميز الإنجليزي.",
    "حوّل في الناتج: x→س، y→ص، f(x)→د(س)، g(x)→ر(س)، sin→جا، cos→جتا، tan→ظا، cot→ظتا، lim→نها، π→ط، e→هـ، dx→دس، dy→دص، وثابت التكامل C→ث عندما يكون المقصود ثابت التكامل.",
    "إذا وصل السؤال أصلًا بالرموز الإنجليزية، يجوز أن تذكرها مرة واحدة فقط عند قراءة المعطيات ثم حوّلها إلى الرموز العربية وأكمل الحل كله بالعربية.",
    "لا تستخدم x أو y أو f(x) أو sin أو cos أو tan أو cot أو lim أو ln أو e أو C في الحل النهائي ما دام لها مقابل عربي واضح في هذا السياق.",
    "للوغاريتم الطبيعي استخدم الصياغة العربية المدرسية المناسبة مثل لو هـ عند الحاجة، ولا ترجع إلى ln لمجرد أن محرك المعادلات أسهل بالإنجليزية.",
    "إذا كان محرّك LaTeX لا يعرض الحروف العربية بصورة سليمة، اكتب المعادلة كسطر Unicode عربي واضح بدل الرجوع للمتغيرات الإنجليزية.",
    "قبل إرسال الإجابة نفّذ فحصًا صامتًا: ابحث عن أي متغيرات أو دوال إنجليزية متبقية في الحل واستبدلها بالمقابل العربي المناسب، ولا تذكر هذا الفحص للطالب.",
  ].join(" ");
}
